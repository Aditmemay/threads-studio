-- Bảng hồ sơ người dùng: tài khoản mới mặc định là member.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price bigint not null default 0 check (price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  service_id bigint references public.services(id) on delete set null,
  note text not null default '',
  status text not null default 'Mới' check (status in ('Mới','Đang xử lý','Hoàn thành','Đã hủy')),
  created_at timestamptz not null default now()
);

-- Tự tạo profile khi đăng ký.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, role) values (new.id, 'member');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.orders enable row level security;

drop policy if exists "Read own profile or admin" on public.profiles;
create policy "Read own profile or admin" on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_admin());
drop policy if exists "Public read active services" on public.services;
create policy "Public read active services" on public.services for select
using (active = true or public.is_admin());
drop policy if exists "Admin insert services" on public.services;
create policy "Admin insert services" on public.services for insert to authenticated
with check (public.is_admin());
drop policy if exists "Admin update services" on public.services;
create policy "Admin update services" on public.services for update to authenticated
using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admin delete services" on public.services;
create policy "Admin delete services" on public.services for delete to authenticated
using (public.is_admin());

drop policy if exists "Members read own orders and admins read all" on public.orders;
create policy "Members read own orders and admins read all" on public.orders for select to authenticated
using (user_id = (select auth.uid()) or public.is_admin());
drop policy if exists "Members create own orders" on public.orders;
create policy "Members create own orders" on public.orders for insert to authenticated
with check (user_id = (select auth.uid()) and status = 'Mới');
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated
using (public.is_admin()) with check (public.is_admin());

